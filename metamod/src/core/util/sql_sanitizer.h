// Вычистка секретов из строк, попадающих в лог, и проверка префикса таблиц.
#pragma once

#include <string>

namespace ch {

class ILogger;

// Заменяет значение пароля в любой строке (сообщение об ошибке, строка подключения).
//
// Причина: параметры подключения собираются из конфига, а тексты ошибок клиента MySQL
// регулярно включают их целиком. Один такой ERROR в консоли сервера — и пароль
// от боевой базы лежит в логах, которые пересылают в чат поддержки.
std::string MaskSecrets(const std::string& text);

// Префикс таблиц попадает в текст SQL как идентификатор — параметризовать его нельзя.
// Поэтому он проходит белый список: латиница, цифры, '_', не длиннее 16 символов.
// Всё остальное — потенциальная инъекция, откатываемся на "ch_" и говорим громко.
//
// В C#-целях та же проверка сделана регулярным выражением, и там пришлось ставить
// якорь \z вместо $: иначе "ch_\n" проезжал бы проверку. Здесь посимвольный обход,
// и перевод строки отсекается наравне с любым другим недопустимым байтом — но тест
// на этот случай оставлен намеренно: он охраняет поведение, а не реализацию.
std::string SanitizePrefix(const std::string& prefix, ILogger* logger = nullptr);

}  // namespace ch
