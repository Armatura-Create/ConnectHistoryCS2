// Работа с адресом игрока: разбор, обезличивание, хеширование.
// Поведение обязано совпадать с IpUtil в C#-целях — колонки player_ip, ip_hash,
// ip_subnet и servers.address читаются одними и теми же запросами.
#pragma once

#include <cstdint>
#include <string>

namespace ch {
namespace ip {

// Достаёт IP из "1.2.3.4:27015", "1.2.3.4" или "[::1]:27015".
// Наивный split по ':' ломает любой IPv6-адрес.
std::string ExtractIp(const std::string& rawAddress);

// Локальные и приватные адреса гео не имеют — их незачем хранить как «страну».
// Неразбираемая строка тоже считается локальной: лучше не собрать данные,
// чем записать мусор.
bool IsLocalOrPrivate(const std::string& ip);

// Подсеть: /24 для IPv4, /48 для IPv6. Пустая строка — адрес не разобран.
std::string ToSubnet(const std::string& ip);

// HMAC-SHA256 от адреса. Пустая соль = хеширование выключено: голый SHA-256
// от IPv4 перебирается за минуты, то есть обратим, и колонка лишь притворялась бы
// анонимной.
std::string Hash(const std::string& ip, const std::string& salt);

// Публичный адрес сервера для справочника servers.
//
// Настройка важнее автоопределения: публичный адрес — внешний факт, который знает
// владелец сервера, а процесс его знать не может. Заполненная, но непригодная
// настройка НЕ подменяется автоопределением: иначе опечатка остаётся незамеченной,
// а в базу уезжает адрес, которого человек не писал.
//
// Пустая строка на выходе — законный ответ «адрес неизвестен».
std::string ResolvePublicAddress(const std::string& configured,
                                 const std::string& engineIp,
                                 int port);

// Приводит "1.2.3.4:27015", "host:27015", "[::1]:27015" или "1.2.3.4" к "host:port".
// Пустая строка — настройка непригодна (в том числе если вписан 0.0.0.0).
std::string NormalizeAddress(const std::string& configured, int fallbackPort);

}  // namespace ip
}  // namespace ch
