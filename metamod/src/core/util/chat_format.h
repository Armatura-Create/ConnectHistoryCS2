// Подстановка цветовых тегов и значений в шаблоны из Messages.json.
#pragma once

#include <map>
#include <string>

namespace ch {
namespace chat {

// Значения подставляются ДО цветов: сами значения тегов не содержат, а вот
// шаблон вокруг них — содержит.
std::string Render(const std::string& templateText,
                   const std::map<std::string, std::string>& values);

// Приводит строку для чата к виду "\x01 " + текст.
//
// Движок CS2 не применяет цвет, стоящий в САМОМ НАЧАЛЕ сообщения: первый цветовой
// код съедается, и строка выходит белой.
//
// Соблазнительная «оптимизация» — ранний выход, если строка уже начинается с кода
// цвета, — отключает починку ровно в том единственном случае, когда она нужна:
// шаблон "{GREEN}[История]" выводился бы белым, а тот же шаблон с пробелом
// в начале — цветным. Так это и ломалось в NotifyMessages.
//
// Функция идемпотентна: повторный вызов не плодит ни кодов, ни пробелов.
std::string EnsureChatColorPrefix(const std::string& input);

}  // namespace chat
}  // namespace ch
