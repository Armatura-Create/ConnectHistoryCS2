// Схема базы. Текст DDL совпадает с C#-целями до символа: три реализации обязаны
// создавать одну и ту же схему, иначе docs/DATABASE.md перестанет быть контрактом.
//
// Правило: DDL идемпотентен. Плагин перезагружают на живом сервере, и повторный
// прогон не имеет права ни упасть, ни изменить существующие данные.
#pragma once

#include <string>
#include <vector>

namespace ch {

// Версия схемы. Поднимается ТОЛЬКО вместе с добавлением шага в Migrations.
constexpr int kSchemaVersion = 3;

// Полный набор DDL для чистой базы. Внешних ключей нет сознательно: они связали бы
// историю с агрегатами и сделали бы невозможной чистку старых сессий без каскадов.
std::vector<std::string> BuildSchema(const std::string& prefix);

struct MigrationStep {
    // Версия, ДО которой поднимаемся
    int target = 0;
    std::string sql;
};

// Шаги миграции для баз, созданных предыдущими версиями плагина.
std::vector<MigrationStep> Migrations(const std::string& prefix);

// Шаг миграции обязан переживать повторное применение, но у ALTER в MySQL нет
// формы IF NOT EXISTS (это MariaDB), а на свежей базе колонка уже приезжает
// из BuildSchema. Поэтому «объект уже существует» — это признак «шаг применён»,
// а не сбой.
//
// Все прочие ошибки обязаны всплывать: молча проглоченная миграция страшнее
// упавшей — вторая видна сразу, первая всплывёт неверными данными.
//
//   1050 — таблица уже есть, 1060 — колонка, 1061 — индекс
bool IsAlreadyAppliedError(unsigned int mysqlErrno);

}  // namespace ch
